CREATE TABLE PART (
    MaPart VARCHAR(50) PRIMARY KEY,
    MaNhom VARCHAR(50) NOT NULL,
    MaBoQC VARCHAR(50) NOT NULL,
    MaNguoiTao VARCHAR(50) NOT NULL,
    MaNguoiDuyet VARCHAR(50),
    TenPart NVARCHAR(255) NOT NULL,
    PhienBan INT NOT NULL DEFAULT 1 CHECK (PhienBan > 0),
    DuongDan NVARCHAR(500) NOT NULL UNIQUE,
    AnhPreview NVARCHAR(500) NOT NULL,
    Nguon NVARCHAR(500) NOT NULL,
    GiayPhep VARCHAR(255) NOT NULL,
    LintTokenDat INT NOT NULL DEFAULT 0 CHECK (LintTokenDat IN (0,1)),
    TrangThaiDuyet VARCHAR(50) NOT NULL DEFAULT 'cho_duyet' CHECK (TrangThaiDuyet IN ('cho_duyet','da_duyet','tu_choi')),
    NgayTao DATE NOT NULL DEFAULT CAST(GETDATE() AS DATE),
    NgayDuyet DATE,
    SoLanKeoTha INT NOT NULL DEFAULT 0 CHECK (SoLanKeoTha >= 0),
    SoLanTuChoi INT NOT NULL DEFAULT 0 CHECK (SoLanTuChoi >= 0),
    
    CONSTRAINT UQ_Part_Nhom_Ten UNIQUE (MaNhom, TenPart),
    
    -- Xử lý logic trạng thái bằng CHECK thay vì code thủ công
    CONSTRAINT CHK_Part_TrangThaiDuyet CHECK (
        (TrangThaiDuyet = 'cho_duyet' AND MaNguoiDuyet IS NULL AND NgayDuyet IS NULL) OR
        (TrangThaiDuyet IN ('da_duyet','tu_choi') AND MaNguoiDuyet IS NOT NULL AND NgayDuyet IS NOT NULL)
    ),
    CONSTRAINT CHK_Part_LintToken CHECK (TrangThaiDuyet <> 'da_duyet' OR LintTokenDat = 1),
    
    CONSTRAINT FK_Part_Nhom FOREIGN KEY (MaNhom) REFERENCES NHOM_PART(MaNhom) ON DELETE NO ACTION,
    CONSTRAINT FK_Part_BoQC FOREIGN KEY (MaBoQC) REFERENCES BO_QUY_CHUAN(MaBoQC) ON DELETE NO ACTION,
    CONSTRAINT FK_Part_NguoiTao FOREIGN KEY (MaNguoiTao) REFERENCES NGUOI_DUNG(MaNguoiDung) ON DELETE NO ACTION,
    CONSTRAINT FK_Part_NguoiDuyet FOREIGN KEY (MaNguoiDuyet) REFERENCES NGUOI_DUNG(MaNguoiDung) ON DELETE NO ACTION
